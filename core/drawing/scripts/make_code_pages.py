#!/usr/bin/env python3
"""Writes the code page tables of $DWGCODEPAGE.

Run this script with a standard Python 3 interpreter from the root of the repository:

    python3 core/drawing/scripts/make_code_pages.py

- DxfCodePageTables.kt: the single-byte code pages. Each table gives the characters of the bytes
  0x80 to 0xFF. A byte that the code page does not define gives U+FFFD.
- DxfDoubleByteTables.kt: the double-byte code pages (ANSI_932, ANSI_936, ANSI_949, ANSI_950,
  ANSI_1361). Each table has 65536 little-endian 16-bit characters: the index b gives the
  character of the single byte b, and the index (lead << 8) | trail gives the character of a
  pair. U+FFFD is a byte or a pair that the code page does not define. The tables are gzip data
  in Base64 text, in parts of 16000 characters.

The script uses only the codecs of the Python standard library.
"""

import base64
import codecs
import gzip
import pathlib
import struct

# The DXF code page names and the Python codec of each one.
CODE_PAGES = [
    ("ANSI_874", "cp874"),
    ("ANSI_1250", "cp1250"),
    ("ANSI_1251", "cp1251"),
    ("ANSI_1252", "cp1252"),
    ("ANSI_1253", "cp1253"),
    ("ANSI_1254", "cp1254"),
    ("ANSI_1255", "cp1255"),
    ("ANSI_1256", "cp1256"),
    ("ANSI_1257", "cp1257"),
    ("ANSI_1258", "cp1258"),
    ("DOS437", "cp437"),
    ("DOS850", "cp850"),
    ("DOS852", "cp852"),
    ("DOS855", "cp855"),
    ("DOS857", "cp857"),
    ("DOS860", "cp860"),
    ("DOS861", "cp861"),
    ("DOS863", "cp863"),
    ("DOS864", "cp864"),
    ("DOS865", "cp865"),
    ("DOS866", "cp866"),
    ("DOS869", "cp869"),
    ("ISO8859-1", "latin_1"),
    ("ISO8859-2", "iso8859_2"),
    ("ISO8859-5", "iso8859_5"),
    ("ISO8859-7", "iso8859_7"),
    ("ISO8859-9", "iso8859_9"),
    ("ISO8859-15", "iso8859_15"),
    ("MACINTOSH", "mac_roman"),
]


def table(codec: str) -> str:
    out = []
    for value in range(0x80, 0x100):
        try:
            char = bytes([value]).decode(codec)
        except UnicodeDecodeError:
            char = "�"
        if len(char) != 1:
            char = "�"
        out.append("\\u%04X" % ord(char))
    return "".join(out)


# The DXF names of the double-byte code pages and the Python codec of each one.
DOUBLE_BYTE_PAGES = [
    ("ANSI_932", "cp932"),
    ("ANSI_936", "cp936"),
    ("ANSI_949", "cp949"),
    ("ANSI_950", "cp950"),
    ("ANSI_1361", "cp1361"),
]


def double_byte_table(codec: str) -> bytes:
    table = [0xFFFD] * 65536
    for value in range(0x100):
        try:
            char = bytes([value]).decode(codec)
        except UnicodeDecodeError:
            continue
        if len(char) == 1:
            table[value] = ord(char)
    for lead in range(0x80, 0x100):
        for trail in range(0x40, 0x100):
            try:
                char = bytes([lead, trail]).decode(codec)
            except UnicodeDecodeError:
                continue
            if len(char) == 1:
                table[(lead << 8) | trail] = ord(char)
    return gzip.compress(struct.pack("<65536H", *table), 9, mtime=0)


def write_double_byte(root: pathlib.Path) -> None:
    target = root / "src/commonMain/kotlin/org/superdro/core/drawing/text/DxfDoubleByteTables.kt"
    lines = [
        "package org.superdro.core.drawing.text",
        "",
        "// This file is generated by core/drawing/scripts/make_code_pages.py. Do not change it by hand.",
        "",
        "/**",
        " * The double-byte code pages of `$DWGCODEPAGE`: gzip data of 65536 little-endian 16-bit",
        " * characters, in Base64 text parts (see make_code_pages.py).",
        " */",
        "internal val DXF_DOUBLE_BYTE_TABLES: Map<String, List<String>> = mapOf(",
    ]
    for name, codec in DOUBLE_BYTE_PAGES:
        text = base64.b64encode(double_byte_table(codec)).decode("ascii")
        parts = [text[i:i + 16000] for i in range(0, len(text), 16000)]
        lines.append('    "%s" to listOf(' % name)
        for part in parts:
            lines.append('        "%s",' % part)
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    target.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    root = pathlib.Path(__file__).resolve().parents[1]
    write_double_byte(root)
    target = root / "src/commonMain/kotlin/org/superdro/core/drawing/text/DxfCodePageTables.kt"
    lines = [
        "package org.superdro.core.drawing.text",
        "",
        "// This file is generated by core/drawing/scripts/make_code_pages.py. Do not change it by hand.",
        "",
        "/**",
        " * The single-byte code pages of `$DWGCODEPAGE`. Each value has 128 characters: the characters of",
        " * the bytes 0x80 to 0xFF. A byte that the code page does not define gives U+FFFD.",
        " */",
        "internal val DXF_CODE_PAGE_TABLES: Map<String, String> = mapOf(",
    ]
    for name, codec in CODE_PAGES:
        codecs.lookup(codec)
        lines.append('    "%s" to' % name)
        data = table(codec)
        # 16 characters (96 source characters) on each line.
        parts = [data[i:i + 6 * 16] for i in range(0, len(data), 6 * 16)]
        lines.append("        " + " +\n        ".join('"%s"' % part for part in parts) + ",")
    lines.append(")")
    lines.append("")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
